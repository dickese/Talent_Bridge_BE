create function update_company_job_count()  returns trigger
    language plpgsql
as
$$
BEGIN
    IF TG_OP = 'INSERT' THEN
UPDATE companies
SET job_count = job_count + 1
WHERE id = NEW.company_id;

ELSIF TG_OP = 'DELETE' THEN
UPDATE companies
SET job_count = job_count - 1
WHERE id = OLD.company_id;
END IF;

RETURN NULL;
END;
$$;

