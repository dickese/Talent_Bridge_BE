-- Create trigger to update updated_at automatically
CREATE OR REPLACE FUNCTION update_email_task_timestamp()
    RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_email_task_update_timestamp
    BEFORE UPDATE ON email_task
    FOR EACH ROW
EXECUTE FUNCTION update_email_task_timestamp();


